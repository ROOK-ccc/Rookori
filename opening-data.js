// 初期配置からの代表例を [UCI形式の手, 日本語解説] で並べます。
// UCI形式では移動元と移動先を続けて書きます（例 e2e4）。
function opening(id, slot, name, english, description, tip, condition, example, ratings) {
  return {
    id, slot, name, english, description, tip, condition,
    moves: example.map(([move]) => move),
    explanations: example.map(([, explanation]) => explanation),
    traits: Object.fromEntries(openingTraits.map((trait, index) => [trait, ratings[index]])),
  };
}

