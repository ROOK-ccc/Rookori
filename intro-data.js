// FENを省略すると通常の初期配置です。選択問題の答えは0から数えます。
function introMove(id, title, text, task, fen, moves, hint, success, completionMessage) {
  return { id, title, text, task, fen, moves: moves.split(' '), hint, success, completionMessage };
}

function introChoice(id, title, text, task, fen, choices, answer, hint, success) {
  return { id, title, text, task, fen, choices, answer, hint, success };
}

